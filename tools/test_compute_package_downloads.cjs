const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../frontend/static/js/compute.js'), 'utf8');
const showResult = source.slice(source.indexOf('function showResult(data)'), source.indexOf('\nfunction showError('));
const elements = {'result-card': {}, 'result-downloads': {}};
const ctx = vm.createContext({document: {getElementById: id => elements[id]}});
vm.runInContext(showResult, ctx);
ctx.showResult({delivery_type: 'zip', output_file: '结果.zip', output_files: ['结果_原版.zip', '结果_纯值.zip']});
let html = elements['result-downloads'].innerHTML;
assert.ok(html.includes('下载原版压缩包'));
assert.ok(html.includes('下载纯值版压缩包'));
assert.ok(html.includes("downloadResult('结果.zip')"));
assert.ok(!html.includes('downloadAllResults('));
ctx.showResult({delivery_type: 'zip', output_file: '结果.zip', output_files: ['结果_原版.zip'], values_copy_failed: true});
html = elements['result-downloads'].innerHTML;
assert.ok(!html.includes('下载纯值版压缩包'));
assert.ok(elements['result-card'].innerHTML.includes('仅提供原版下载'));
ctx.showResult({output_file: '单表.xlsx', output_files: ['单表.xlsx', '单表_纯值.xlsx']});
html = elements['result-downloads'].innerHTML;
assert.ok(html.includes('下载原版</button>') && html.includes('下载纯值版</button>'));
assert.ok(html.includes('downloadAllResults('));
console.log('PASS: separate ZIP downloads, combined ZIP, failed values copy, single workbook');
